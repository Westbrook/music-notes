import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
// Pinned Playwright/browser pair; external runtime path is optional for Codex.
const engines = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const engine = process.env.LISTEN_TEST_BROWSER || 'chromium';
assert.ok(['chromium', 'firefox', 'webkit'].includes(engine));
const base = process.env.LISTEN_TEST_URL || 'http://127.0.0.1:5173';
const output = resolve(process.env.LISTEN_TEST_OUTPUT || '/tmp/music-notes-listen-browser');
await mkdir(output, { recursive: true });
const browser = await engines[engine].launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, acceptDownloads: true });
  const page = await context.newPage();
  let phase = 'startup';
  const errors = []; page.on('pageerror', error => errors.push({ phase, message: error.message }));
  const requests = []; page.on('request', request => requests.push(request.url()));
  await page.goto(`${base}/tests/authoring-listen-browser.html`);
  await page.waitForSelector('body[data-author-ready="true"][data-render-state="ready"]');
  const accepted = await page.locator('music-staff#trombone-study').evaluate(el => el.outerHTML);
  const music = await page.locator('music-staff#trombone-study').evaluate(el => el.innerHTML);
  phase = 'enter Listen';
  await page.getByRole('button', { name: 'Listen', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#listen-status').textContent.startsWith('Ready'));
  assert.equal(await page.locator('#listen-tempo').inputValue(), '80');
  phase = 'transport';
  await page.locator('#listen-play').click();
  await page.waitForFunction(() => document.querySelector('#listen-play').textContent === 'Pause');
  await page.locator('.author-playing').first().waitFor();
  const firstId = await page.locator('.author-playing').first().getAttribute('data-source-id');
  assert.equal(firstId, 'trombone-m1-n1');
  await page.screenshot({ path: `${output}/listen-desktop.png` });
  phase = 'transport';
  await page.locator('#listen-play').click();
  assert.equal(await page.locator('#listen-play').textContent(), 'Resume');
  phase = 'transport';
  await page.locator('#listen-play').click();
  await page.waitForFunction(() => document.querySelector('#listen-play').textContent === 'Pause');
  await page.locator('#listen-stop').click();
  assert.equal(await page.locator('.author-playing').count(), 0);
  assert.equal(await page.locator('#listen-time').textContent(), '0:00 / 0:08');
  phase = 'download';
  let downloaded = page.waitForEvent('download');
  await page.locator('#listen-download').click();
  const original = await downloaded; await original.saveAs(`${output}/current-score.wav`);
  const wav = await readFile(`${output}/current-score.wav`);
  assert.equal(wav.toString('ascii', 0, 4), 'RIFF');
  assert.equal(wav.readUInt32LE(24), 44100);
  assert.equal(wav.readUInt32LE(40) / 2 / 44100, 8.37);
  // Inspect actual audio periodicity: the first rendered note is G3, not G2.
  const samples = Array.from({ length: 8000 }, (_, i) => wav.readInt16LE(44 + 2 * (2205 + i)) / 32768);
  let bestLag = 0, best = -Infinity;
  for (let lag = 170; lag <= 270; lag++) {
    let product = 0, squareA = 0, squareB = 0;
    for (let i = 0; i < samples.length - lag; i++) { product += samples[i] * samples[i + lag]; squareA += samples[i] ** 2; squareB += samples[i + lag] ** 2; }
    const similarity = product / Math.sqrt(squareA * squareB);
    if (similarity > best) { best = similarity; bestLag = lag; }
  }
  assert.ok(Math.abs(44100 / bestLag - 196) < 2);
  phase = 'tempo';
  await page.locator('#listen-tempo').fill('160'); await page.locator('#listen-tempo').press('Tab');
  assert.equal(await page.locator('#listen-time').textContent(), '0:00 / 0:04');
  downloaded = page.waitForEvent('download'); await page.locator('#listen-download').click();
  const faster = await downloaded; await faster.saveAs(`${output}/faster.wav`);
  const fast = await readFile(`${output}/faster.wav`); assert.equal(fast.readUInt32LE(40) / 2 / 44100, 4.2450113378684806);
  await page.locator('#listen-score-tempo').click();
  assert.equal(await page.locator('#listen-tempo').inputValue(), '80');
  phase = 'mobile resize';
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: `${output}/listen-mobile.png` });
  assert.ok(await page.getByRole('button', { name: 'Listen', exact: true }).isVisible());
  assert.ok(await page.locator('#listen-download').isVisible());
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  phase = 'return to Write';
  await page.getByRole('button', { name: 'Write', exact: true }).click();
  assert.equal(await page.locator('music-staff#trombone-study').evaluate(el => el.innerHTML), music);
  // Real Source controls must invalidate playback, including pending text.
  phase = 'source editor';
  await page.getByRole('button', { name: 'Source', exact: true }).click();
  await page.locator('#source-input').fill(accepted.replaceAll('G3', 'G4'));
  await page.locator('#close-source').click();
  phase = 'enter Listen';
  await page.getByRole('button', { name: 'Listen', exact: true }).click();
  assert.equal(await page.locator('#listen-play').isDisabled(), true);
  assert.match(await page.locator('#listen-status').textContent(), /unapplied/);
  phase = 'return to Write';
  await page.getByRole('button', { name: 'Write', exact: true }).click();
  phase = 'source editor';
  await page.getByRole('button', { name: 'Source', exact: true }).click();
  phase = 'apply source';
  await page.getByRole('button', { name: 'Apply source', exact: true }).click();
  await page.locator('#close-source').click();
  phase = 'enter Listen';
  await page.getByRole('button', { name: 'Listen', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('#listen-play').disabled);
  downloaded = page.waitForEvent('download'); await page.locator('#listen-download').click();
  const edited = await downloaded; await edited.saveAs(`${output}/edited-score.wav`);
  assert.notDeepEqual(await readFile(`${output}/edited-score.wav`), wav);
  phase = 'unfinished measures';
  await page.getByRole('button', { name: 'Write', exact: true }).click();
  const unfinished = await page.locator('music-staff#trombone-study').evaluate(el => {
    const copy = el.cloneNode(true);
    [...copy.querySelectorAll('music-measure')].forEach((measure, index) => {
      measure.setAttribute('incomplete', '');
      const events = [...measure.querySelectorAll('music-note, music-rest')];
      events.forEach((event, eventIndex) => {
        if (index === 1 || eventIndex > 0) event.remove();
        else event.removeAttribute('beam');
      });
    });
    return copy.outerHTML;
  });
  await page.getByRole('button', { name: 'Source', exact: true }).click();
  await page.locator('#source-input').fill(unfinished);
  await page.getByRole('button', { name: 'Apply source', exact: true }).click();
  assert.equal(await page.locator('#source-error').isVisible(), false);
  await page.locator('#close-source').click();
  const unfinishedMusic = await page.locator('music-staff#trombone-study').evaluate(el => el.innerHTML);
  await page.getByRole('button', { name: 'Listen', exact: true }).click();
  assert.equal(await page.locator('#listen-play').isDisabled(), false);
  assert.match(await page.locator('#listen-notices').textContent(), /play as rests/);
  assert.equal(await page.locator('#listen-time').textContent(), '0:00 / 0:08');
  downloaded = page.waitForEvent('download'); await page.locator('#listen-download').click();
  await (await downloaded).saveAs(`${output}/unfinished-score.wav`);
  const padded = await readFile(`${output}/unfinished-score.wav`);
  assert.equal(padded.readUInt32LE(40) / 2 / 44100, 8.37);
  const peak = (start, end) => {
    let maximum = 0;
    for (let sample = Math.ceil(start * 44100); sample < Math.floor(end * 44100); sample++) maximum = Math.max(maximum, Math.abs(padded.readInt16LE(44 + sample * 2)));
    return maximum;
  };
  assert.ok(peak(.05, .5) > 100, 'Opening note is audible');
  assert.equal(peak(1, 5.24), 0, 'Short first bar and empty second bar contain padded silence');
  assert.ok(peak(5.3, 5.4) > 100, 'Bar 3 keeps its full-meter onset');
  assert.equal(peak(5.6, 8.25), 0, 'Final incomplete bar retains its silent remainder');
  await page.locator('#listen-play').click();
  await page.locator('.author-playing').first().waitFor();
  await page.waitForFunction(() => document.querySelector('#listen-time').textContent.startsWith('0:01'));
  assert.equal(await page.locator('.author-playing').count(), 0, 'Padded silence has no invented note highlight');
  assert.equal(await page.locator('#listen-play').textContent(), 'Pause');
  await page.screenshot({ path: `${output}/unfinished-playback.png` });
  await page.locator('#listen-stop').click();
  assert.equal(await page.locator('music-staff#trombone-study').evaluate(el => el.innerHTML), unfinishedMusic);
  phase = 'reported 5/4 notation notice';
  await page.getByRole('button', { name: 'Write', exact: true }).click();
  await page.getByRole('button', { name: 'Source', exact: true }).click();
  await page.locator('#source-input').fill('<music-staff id="five-four" clef="bass"><music-measure meter="5/4" incomplete><music-note pitch="G3" duration="half"></music-note></music-measure></music-staff>');
  await page.getByRole('button', { name: 'Apply source', exact: true }).click();
  await page.locator('#close-source').click();
  await page.waitForSelector('body[data-render-state="ready"]');
  const fiveFourMusic = await page.locator('music-staff#five-four').evaluate(el => el.innerHTML);
  await page.getByRole('button', { name: 'Listen', exact: true }).click();
  await page.waitForSelector('body[data-render-state="ready"]');
  assert.match(await page.locator('#notation-review-list').textContent(), /Voice contains 1\/2 of 5\/4 whole notes\. This measure is an incomplete draft\./);
  assert.equal(await page.locator('#listen-play').isDisabled(), false);
  assert.equal(await page.locator('#listen-download').isDisabled(), false);
  await page.locator('#listen-play').click();
  await page.waitForFunction(() => document.querySelector('#listen-play').textContent === 'Pause');
  await page.locator('.author-playing').first().waitFor();
  await page.locator('#listen-stop').click();
  downloaded = page.waitForEvent('download'); await page.locator('#listen-download').click();
  await (await downloaded).saveAs(`${output}/five-four-draft.wav`);
  const fiveFour = await readFile(`${output}/five-four-draft.wav`);
  assert.equal(fiveFour.readUInt32LE(40) / 2 / 44100, 3.87);
  assert.ok(fiveFour.subarray(44, 44 + 2 * 44100).some(value => value !== 0), 'Written note is audible');
  assert.ok(fiveFour.subarray(44 + 2 * 2 * 44100).every(value => value === 0), 'Unwritten beats remain silent');
  assert.equal(await page.locator('music-staff#five-four').evaluate(el => el.innerHTML), fiveFourMusic);
  assert.equal(requests.some(url => !url.startsWith(base) && !url.startsWith('blob:')), false);
  assert.deepEqual(errors, []);
  const result = { engine, browser: browser.version(), passed: true, checks: ['current G3 pitch in WAV', 'play/pause/resume/stop', 'highlighting', 'tempo and download duration', 'music unchanged by Listen', 'pending Source blocks playback', 'applied source invalidates audio', 'mobile controls and no page overflow', 'incomplete and empty measures play', 'WAV contains exact silent gaps and aligned later notes', 'no highlight during padded silence', 'reported 1/2 of 5/4 notation notice allows playback and WAV download', 'no external audio requests', 'no browser errors'] };
  await writeFile(`${output}/result.json`, JSON.stringify(result, null, 2)); console.log(JSON.stringify(result));
} finally { await browser.close(); }
