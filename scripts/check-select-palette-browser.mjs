import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';
const base=process.env.SELECT_TEST_URL || 'http://127.0.0.1:5173';
const output=process.env.SELECT_TEST_OUTPUT || '/tmp/music-notes-select-palette';
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true});
try {
 const page=await browser.newPage({viewport:{width:1600,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`${base}/tests/authoring-listen-browser.html`);
 const ready=()=>page.waitForSelector('body[data-author-ready="true"][data-render-state="ready"]');await ready();
 await page.locator('#source-trigger').click();
 await page.locator('#source-input').fill('<music-staff id="staff" clef="bass"><music-measure id="bar" incomplete><music-note id="a" pitch="F3" duration="quarter"><music-articulation id="accent" type="accent"></music-articulation><music-articulation id="tenuto" type="tenuto"></music-articulation></music-note><music-note id="b" pitch="G3" duration="eighth"></music-note><music-note id="c" pitch="A3" duration="eighth"></music-note></music-measure></music-staff>');
 await page.locator('#source-apply').click();await page.locator('#close-source').click();await ready();
 const note=id=>page.locator(`#score-host .screen g.vf-music-event[data-source-id="${id}"]`);
 const source=page.locator('music-staff#staff');const html=()=>source.evaluate(el=>el.outerHTML);
 const group=id=>page.locator(`#${id}`);
 const choice=(id,value)=>group(id).locator(`.controls > button[value="${value}"]`);
 await note('a').click();
 const before=await html();
 await choice('selection-accidentals','1').click();await ready();
 assert.equal(await source.locator('#a').getAttribute('pitch'),'F#3');
 await page.locator('#undo').click();await ready();assert.equal(await html(),before);
 await page.locator('#selection-natural').focus();await page.keyboard.press('ArrowRight');
 assert.equal(await page.locator('#selection-sharp').evaluate(el=>el===el.getRootNode().activeElement),true);
 await page.keyboard.press('Enter');await ready();assert.equal(await source.locator('#a').getAttribute('pitch'),'F#3');
 await page.locator('#undo').click();await ready();assert.equal(await html(),before);
 await choice('selection-quick-duration','eighth').click();await ready();
 await choice('selection-quick-dots','1').click();await ready();
 assert.equal(await source.locator('#a').getAttribute('dots'),'1');
 await choice('selection-quick-attack','articulation:accent').click();await ready();
 assert.equal(await source.locator('#a music-articulation[type="accent"]').count(),0);
 assert.equal(await source.locator('#a #tenuto').count(),1);
 assert.equal(await page.locator('#workspace-tools').isVisible(),false);
 assert.equal(await group('entry-duration').getAttribute('value'),'quarter');
 await page.screenshot({path:`${output}/select-desktop.png`});
 await note('b').click({modifiers:['Shift']});
 assert.equal(await choice('selection-quick-attack','articulation:staccato').getAttribute('aria-pressed'),'false');
 await choice('selection-quick-attack','articulation:staccato').click();await ready();
 assert.equal(await source.locator('music-articulation[type="staccato"]').count(),2);
 await group('selection-quick-attack').locator('select').selectOption('ornament:trill');await ready();
 assert.equal(await source.locator('music-ornament[type="trill"]').count(),2);
 await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(200);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 const controls=await page.locator('#selection-quick-tools').boundingBox();
 const dock=await page.locator('#workspace-dock').boundingBox();
 assert.ok(controls.y>=dock.y && controls.y+controls.height<=dock.y+dock.height);
 await page.screenshot({path:`${output}/select-mobile.png`});
 const beforeNone=await html();
 await group('selection-quick-attack').locator('select').selectOption('none');await ready();
 assert.equal(await source.locator('music-articulation, music-ornament').count(),0);
 await page.locator('#undo').click();await ready();assert.equal(await html(),beforeNone);
 // A selection edit must not change the recipe when returning to writing.
 await page.locator('#toggle-entry').click();
 assert.equal(await group('entry-duration').getAttribute('value'),'quarter');
 assert.equal(await group('entry-attack').getAttribute('value'),'none');
 assert.equal(await group('entry-dots').getAttribute('value'),'0');
 await page.setViewportSize({width:1280,height:900});
 await page.evaluate(()=>{document.documentElement.style.fontSize='24px';});
 await page.locator('#select-mode').click();await page.waitForTimeout(200);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:`${output}/select-large-text.png`});
 assert.deepEqual(errors,[]);
 const result={passed:true,browser:browser.version(),checks:['direct selected accidental/duration/dots','native arrow navigation and Enter activation','larger text toolbar fit','independent articulation toggles','exact multi-selection ornaments','one-step undo','writing recipe preserved','no Properties form required','390px overflow controls and contained toolbar','no browser errors']};
 await writeFile(`${output}/result.json`,JSON.stringify(result,null,2));console.log(JSON.stringify(result));
}finally{await browser.close();}
